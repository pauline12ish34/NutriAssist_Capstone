"""Build food and nutrient tables from the traceable workbook loader output."""

from __future__ import annotations

import hashlib
from pathlib import Path

import pandas as pd

from .clean_nutrients import (
    UNIT_CONVERSIONS,
    clean_sheet,
    source_column,
    to_canonical,
    value_quality,
)
from .load_workbook import (
    DEFAULT_INTERIM_DIR,
    DEFAULT_WORKBOOK,
    VALIDATION_REPORT,
    load_workbook,
)

DEFAULT_OUTPUT_DIR = Path("data/processed")
SOURCE_TYPE = "nutritionist_workbook"


def _food_id(sheet: str, row: int, name: str) -> str:
    key = f"{sheet}:{row}:{name.strip().lower()}".encode("utf-8")
    return f"food_{hashlib.sha1(key).hexdigest()[:12]}"


def _write_cleaning_report(foods: pd.DataFrame, nutrients: pd.DataFrame, path: Path) -> None:
    flag_counts = (
        foods["quality_flags"].str.split(";").explode().loc[lambda flags: flags != ""].value_counts()
    )
    lines = [
        "# Nutrient cleaning report",
        "",
        "Generated by `src/nutriassist/food_data/build_foods.py`. Rules and evidence: `docs/nutrient_cleaning.md`.",
        "",
        f"- Foods: {len(foods)}",
        f"- Nutrient values: {len(nutrients)}",
        "",
        "## Per-100 g confidence",
        "",
        "| Confidence | Foods |",
        "|---|---:|",
    ]
    for level, count in foods["basis_confidence"].value_counts().items():
        lines.append(f"| {level} | {count} |")
    lines += ["", "## Food quality flags", "", "| Flag | Foods |", "|---|---:|"]
    for flag, count in flag_counts.items():
        lines.append(f"| `{flag}` | {count} |")
    lines += ["", "## Nutrient value quality", "", "| Quality | Values |", "|---|---:|"]
    for quality, count in nutrients["value_quality"].value_counts().items():
        lines.append(f"| `{quality}` | {count} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def build_food_tables(
    workbook_path: str | Path = DEFAULT_WORKBOOK,
    ignored_sheets: tuple[str, ...] = (),
    output_dir: str | Path = DEFAULT_OUTPUT_DIR,
    interim_dir: str | Path = DEFAULT_INTERIM_DIR,
    validation_report: str | Path = VALIDATION_REPORT,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Create the cleaned foods and nutrient tables and write them as CSV files.

    Workbook values are per serving; each value is converted to its canonical
    unit and reported both per serving and per 100 g.
    """
    loaded = load_workbook(
        workbook_path,
        ignored_sheets=ignored_sheets,
        interim_dir=interim_dir,
        validation_report=validation_report,
    )
    food_rows: list[dict[str, object]] = []
    nutrient_rows: list[dict[str, object]] = []

    for sheet_name, frame in loaded.items():
        required = {"food", "source_sheet", "source_row"}
        missing = required.difference(frame.columns)
        if missing:
            raise ValueError(
                f"Cannot build foods from `{sheet_name}`; missing columns: {sorted(missing)}"
            )

        cleaned = clean_sheet(frame)
        measured_columns = [column for column in UNIT_CONVERSIONS if column in cleaned.columns]
        for _, row in cleaned.iterrows():
            name = row["food"]
            if pd.isna(name) or not str(name).strip():
                raise ValueError(f"Cannot build foods: row {row['source_row']} has no food name.")
            source_sheet = str(row["source_sheet"])
            source_row = int(row["source_row"])
            food_id = _food_id(source_sheet, source_row, str(name))
            source = f"{source_sheet}!{source_row}"
            serving_g = row["serving_g_estimated"]
            shifted = bool(row["shift_corrected"])
            food_rows.append(
                {
                    "food_id": food_id,
                    "local_name": None,
                    "english_name": str(name).strip(),
                    "food_group": sheet_name,
                    "is_local": False,
                    "serving_g_estimated": serving_g,
                    "basis_confidence": row["basis_confidence"],
                    "quality_flags": row["quality_flags"],
                    "nutrition_density_score": row.get("nutrition_density"),
                    "source": source,
                    "source_type": SOURCE_TYPE,
                }
            )
            for nutrient in measured_columns:
                workbook_amount = row[nutrient]
                per_serving, unit = to_canonical(nutrient, workbook_amount)
                per_100g = per_serving * 100 / serving_g if pd.notna(serving_g) else None
                nutrient_rows.append(
                    {
                        "food_id": food_id,
                        "nutrient_name": nutrient,
                        "amount_per_serving": None if pd.isna(per_serving) else round(per_serving, 4),
                        "amount_per_100g": None if pd.isna(per_100g) else round(per_100g, 4),
                        "unit": unit,
                        "value_quality": value_quality(nutrient, workbook_amount, shifted),
                        "source_column": source_column(nutrient, shifted),
                        "source_sheet": source_sheet,
                        "source_row": source_row,
                        "source": source,
                        "source_type": SOURCE_TYPE,
                    }
                )

    foods = pd.DataFrame(food_rows)
    nutrients = pd.DataFrame(nutrient_rows)
    if foods["source"].isna().any() or nutrients["source"].isna().any():
        raise ValueError("Cannot write output: every row must have a source.")

    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    foods.to_csv(output / "foods.csv", index=False)
    nutrients.to_csv(output / "food_nutrients.csv", index=False)
    _write_cleaning_report(foods, nutrients, output / "cleaning_report.md")
    return foods, nutrients


if __name__ == "__main__":
    build_food_tables()
