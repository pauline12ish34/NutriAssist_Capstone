"""Build the bilingual child-nutrition QA dataset used for fine-tuning.

Inputs (all hand-curated, nothing is generated by a model at build time):
- the original 135 pairs, triaged by ``curated/revisions.jsonl`` (keep / edit / redirect / drop);
- new English and Kinyarwanda pairs in ``curated/new_en.jsonl`` and ``curated/new_rw.jsonl``;
- nutrient pairs templated from USDA-checked rows of the cleaned food table,
  listed in ``data/reference/food_names_rw.csv``.

Pairs that share a ``group`` (a question, its paraphrases and its translation)
always land in the same split, so the test set never leaks into training.
"""

from __future__ import annotations

import argparse
import json
import random
from collections import Counter, defaultdict
from pathlib import Path

import pandas as pd

from ..prompts import SYSTEM_PROMPT, build_messages
from .review_sheet import REVIEW_SHEET, apply_review

QA_DIR = Path("data/QA_data")
ORIGINAL = QA_DIR / "malnutrition_dataset_final.jsonl"
CURATED_DIR = QA_DIR / "curated"
OUTPUT_DIR = QA_DIR / "processed"
FOOD_NAMES = Path("data/reference/food_names_rw.csv")
FOODS = Path("data/processed/foods.csv")
NUTRIENTS = Path("data/processed/food_nutrients.csv")

SEED = 42
SPLIT_FRACTIONS = {"train": 0.75, "val": 0.1, "test": 0.15}

NUTRIENT_LABELS = {
    "caloric_value": ("energy", "ingufu", "kcal", 0),
    "protein": ("protein", "poroteyine", "g", 1),
    "iron": ("iron", "ubutare", "mg", 1),
    "calcium": ("calcium", "kalisiyumu", "mg", 0),
    "vitamin_c": ("vitamin C", "vitamini C", "mg", 0),
}

HIGHLIGHT_TIPS_EN = {
    "protein": "Protein helps children grow and repair their bodies.",
    "iron": "Serve it with a vitamin C fruit such as orange or guava to help the body absorb the iron.",
    "calcium": "Calcium builds strong bones and teeth.",
    "vitamin_c": "Vitamin C protects against infections and helps the body absorb iron from beans and greens.",
    "caloric_value": "Add a little oil or groundnut paste and a protein food to make a complete meal for a child.",
}
HIGHLIGHT_TIPS_RW = {
    "protein": "Poroteyine ifasha abana gukura no gusana umubiri.",
    "iron": "Bitange hamwe n'urubuto rufite vitamini C nk'icunga cyangwa ipera kugira ngo umubiri ukure ubutare neza.",
    "calcium": "Kalisiyumu yubaka amagufa n'amenyo akomeye.",
    "vitamin_c": "Vitamini C irinda indwara kandi ifasha umubiri gukura ubutare mu bishyimbo n'imboga.",
    "caloric_value": "Ongeramo amavuta make cyangwa ubunyobwa biseye n'ibiryo byubaka umubiri kugira ngo ribe ifunguro ryuzuye ku mwana.",
}


def _read_jsonl(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def _write_jsonl(path: Path, rows: list[dict]) -> None:
    with path.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")


def _record(group: str, lang: str, category: str, source: str, question: str, answer: str,
            paraphrases: list[str] | None = None, review: str = "") -> dict:
    return {
        "id": f"{lang}-{group}",
        "group": group,
        "lang": lang,
        "category": category,
        "source": source,
        "question": question.strip(),
        "paraphrases": [p.strip() for p in (paraphrases or [])],
        "answer": answer.strip(),
        "review": review,
    }


def original_records(original_path: Path, revisions_path: Path) -> tuple[list[dict], list[dict]]:
    """Apply the triage decisions to the original pairs. Returns (records, dropped)."""
    original = _read_jsonl(original_path)
    revisions = {row["src"]: row for row in _read_jsonl(revisions_path)}
    missing = set(range(len(original))) - set(revisions)
    extra = set(revisions) - set(range(len(original)))
    if missing or extra:
        raise ValueError(f"Revisions must cover every original pair once; missing={sorted(missing)} extra={sorted(extra)}")

    records, dropped = [], []
    for index, pair in enumerate(original):
        revision = revisions[index]
        action = revision["action"]
        if action == "drop":
            dropped.append({"src": index, "question": pair["messages"][0]["content"], "reason": revision["reason"]})
            continue
        if action == "keep":
            question, answer = pair["messages"][0]["content"], pair["messages"][-1]["content"]
        elif action in ("edit", "redirect"):
            question, answer = revision["q"], revision["a"]
        else:
            raise ValueError(f"Unknown action {action!r} for original pair {index}")
        source = "original" if action == "keep" else f"original_{action}"
        records.append(_record(f"orig-{index}", "en", revision["category"], source, question, answer))
    return records, dropped


def curated_records(path: Path, lang: str) -> list[dict]:
    review = "pending_native_review" if lang == "rw" else ""
    return [
        _record(row["group"], lang, row["category"], "curated", row["q"], row["a"], row.get("paraphrases"), review)
        for row in _read_jsonl(path)
    ]


def _fmt(value: float, decimals: int) -> str:
    return f"{value:.{decimals}f}" if decimals else f"{round(value):d}"


def _za(noun: str) -> str:
    """Kinyarwanda possessive 'za', elided before a vowel (za + ibishyimbo -> z'ibishyimbo)."""
    return f"z'{noun}" if noun[0] in "aeiou" else f"za {noun}"


def nutrient_records(names_path: Path, foods_path: Path, nutrients_path: Path) -> list[dict]:
    """Template per-100 g nutrient answers from USDA-checked rows with reliable values only."""
    names = pd.read_csv(names_path, keep_default_na=False)
    names = names[(names["usda_checked"] == "yes") & (names["food_id"] != "")]
    foods = pd.read_csv(foods_path).set_index("food_id")
    nutrients = pd.read_csv(nutrients_path)
    nutrients = nutrients[
        nutrients["nutrient_name"].isin(NUTRIENT_LABELS) & (nutrients["value_quality"] == "ok")
    ]

    records = []
    for _, food in names.iterrows():
        if foods.loc[food["food_id"], "basis_confidence"] != "high":
            raise ValueError(f"{food['food_id']} is not high-confidence; remove it from {names_path}")
        values = nutrients[nutrients["food_id"] == food["food_id"]].set_index("nutrient_name")["amount_per_100g"]
        present = [n for n in NUTRIENT_LABELS if n in values.index and values[n] > 0]
        group = f"nut-{food['food_id'].removeprefix('food_')}"
        en_name, rw_name, highlight = food["display_en"], food["rw_name"], food["highlight"]

        parts_en = [f"{_fmt(values[n], NUTRIENT_LABELS[n][3])} {NUTRIENT_LABELS[n][2]} of {NUTRIENT_LABELS[n][0]}" for n in present]
        answer_en = (
            f"100 g of {en_name} provides about {', '.join(parts_en[:-1])} and {parts_en[-1]}. "
            f"{HIGHLIGHT_TIPS_EN[highlight]}"
        )
        records.append(_record(group, "en", "food_nutrients", "food_table",
                               f"What nutrients are in {en_name}?", answer_en,
                               [f"Is {en_name} nutritious for children?"]))

        label, _, unit, decimals = NUTRIENT_LABELS[highlight]
        amount = _fmt(values[highlight], decimals)
        records.append(_record(f"{group}-{highlight}", "en", "food_nutrients", "food_table",
                               f"How much {label} is in 100 g of {en_name}?",
                               f"100 g of {en_name} has about {amount} {unit} of {label}. "
                               f"{HIGHLIGHT_TIPS_EN[highlight]}"))

        if rw_name:
            parts_rw = [f"{NUTRIENT_LABELS[n][1]} {_fmt(values[n], NUTRIENT_LABELS[n][3])} {NUTRIENT_LABELS[n][2]}" for n in present]
            answer_rw = (
                f"Muri garama 100 {_za(rw_name)} harimo hafi {', '.join(parts_rw[:-1])} na {parts_rw[-1]}. "
                f"{HIGHLIGHT_TIPS_RW[highlight]}"
            )
            records.append(_record(group, "rw", "food_nutrients", "food_table",
                                   f"Ni izihe ntungamubiri ziri muri {rw_name}?", answer_rw,
                                   [f"Garama 100 {_za(rw_name)} zirimo iki?"], review="pending_native_review"))
    return records


def validate(records: list[dict]) -> None:
    seen: dict[str, str] = {}
    for record in records:
        if not record["question"] or not record["answer"]:
            raise ValueError(f"Empty question or answer in {record['id']}")
        for question in [record["question"], *record["paraphrases"]]:
            key = " ".join(question.lower().split())
            if key in seen and seen[key] != record["id"]:
                raise ValueError(f"Duplicate question in {record['id']} and {seen[key]}: {question!r}")
            seen[key] = record["id"]
    ids = Counter(record["id"] for record in records)
    duplicates = [key for key, count in ids.items() if count > 1]
    if duplicates:
        raise ValueError(f"Duplicate ids: {duplicates}")


def assign_splits(records: list[dict], seed: int = SEED) -> dict[str, str]:
    """Split by group, stratified by category, so translations and paraphrases stay together."""
    groups_by_category: dict[str, list[str]] = defaultdict(list)
    for group, category in sorted({(r["group"], r["category"]) for r in records}):
        groups_by_category[category].append(group)

    rng = random.Random(seed)
    split_of: dict[str, str] = {}
    for category in sorted(groups_by_category):
        groups = groups_by_category[category]
        rng.shuffle(groups)
        n_test = round(len(groups) * SPLIT_FRACTIONS["test"]) or (1 if len(groups) >= 5 else 0)
        n_val = round(len(groups) * SPLIT_FRACTIONS["val"]) or (1 if len(groups) >= 8 else 0)
        for index, group in enumerate(groups):
            split_of[group] = "test" if index < n_test else "val" if index < n_test + n_val else "train"
    return split_of


def to_chat(question: str, answer: str) -> dict:
    return {"messages": build_messages(question, answer)}


def _markdown_table(frame: pd.DataFrame) -> list[str]:
    header = [frame.index.name or "", *map(str, frame.columns)]
    lines = ["| " + " | ".join(header) + " |", "|---|" + "---:|" * len(frame.columns)]
    lines += ["| " + " | ".join([str(index), *map(str, row)]) + " |" for index, row in frame.iterrows()]
    return lines


def _report(records: list[dict], dropped: list[dict], splits: dict[str, list[dict]], path: Path) -> None:
    lines = ["# QA dataset report", "", "Generated by `src/nutriassist/qa_data/build_qa_dataset.py`. Design notes: `docs/qa_dataset.md`.", ""]
    lines += [f"- Unique QA pairs: {len(records)}", f"- Original pairs dropped: {len(dropped)}"]
    lines += [f"- Chat examples in {name}.jsonl: {len(rows)}" for name, rows in splits.items()]

    table = pd.DataFrame(records)
    by_category = table.pivot_table(index="category", columns="lang", values="id", aggfunc="count",
                                    fill_value=0, margins=True, margins_name="total")
    by_split = table.pivot_table(index="split", columns="lang", values="id", aggfunc="count", fill_value=0)
    lines += ["", "## Pairs by category and language", "", *_markdown_table(by_category), ""]
    lines += ["## Pairs by split and language", "", *_markdown_table(by_split), ""]
    lines += ["## Pairs by source", "", *_markdown_table(table["source"].value_counts().to_frame("pairs")), ""]
    review = table.loc[table["lang"] == "rw", "review"].value_counts().to_frame("pairs")
    lines += ["## Kinyarwanda review status", "", *_markdown_table(review), ""]
    lines += ["## Dropped original pairs", "", "| # | Question | Reason |", "|---:|---|---|"]
    lines += [f"| {d['src']} | {d['question']} | {d['reason']} |" for d in dropped]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def collect_records(
    original_path: str | Path = ORIGINAL,
    curated_dir: str | Path = CURATED_DIR,
    food_names_path: str | Path = FOOD_NAMES,
    foods_path: str | Path = FOODS,
    nutrients_path: str | Path = NUTRIENTS,
) -> tuple[list[dict], list[dict]]:
    """All QA records before review is applied. Returns (records, dropped originals)."""
    curated = Path(curated_dir)
    records, dropped = original_records(Path(original_path), curated / "revisions.jsonl")
    records += curated_records(curated / "new_en.jsonl", "en")
    for path in sorted(curated.glob("new_rw*.jsonl")):
        records += curated_records(path, "rw")
    records += nutrient_records(Path(food_names_path), Path(foods_path), Path(nutrients_path))
    return records, dropped


def build_qa_dataset(
    original_path: str | Path = ORIGINAL,
    curated_dir: str | Path = CURATED_DIR,
    output_dir: str | Path = OUTPUT_DIR,
    food_names_path: str | Path = FOOD_NAMES,
    foods_path: str | Path = FOODS,
    nutrients_path: str | Path = NUTRIENTS,
    review_path: str | Path = REVIEW_SHEET,
    reviewed_only: bool = False,
) -> dict[str, list[dict]]:
    """Build the splits. ``reviewed_only`` drops Kinyarwanda pairs not yet approved or corrected."""
    records, dropped = collect_records(original_path, curated_dir, food_names_path, foods_path, nutrients_path)
    records = apply_review(records, review_path, reviewed_only)
    validate(records)

    split_of = assign_splits(records)
    splits: dict[str, list[dict]] = {"train": [], "val": [], "test": []}
    paraphrase_eval: list[dict] = []
    for record in records:
        record["split"] = split_of[record["group"]]
        # Metadata lets evaluation report scores per language and category.
        meta = {"id": record["id"], "lang": record["lang"], "category": record["category"]}
        splits[record["split"]].append({**to_chat(record["question"], record["answer"]), **meta})
        if record["split"] == "train":
            splits["train"].extend({**to_chat(p, record["answer"]), **meta} for p in record["paraphrases"])
        else:
            # Held-out paraphrases test robustness to rewording without leaking into training.
            paraphrase_eval.extend(
                {**to_chat(p, record["answer"]), **meta, "split": record["split"]} for p in record["paraphrases"]
            )
    random.Random(SEED).shuffle(splits["train"])

    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    _write_jsonl(output / "qa_master.jsonl", records)
    for name, rows in splits.items():
        _write_jsonl(output / f"{name}.jsonl", rows)
    _write_jsonl(output / "heldout_paraphrases.jsonl", paraphrase_eval)
    _report(records, dropped, splits, output / "qa_report.md")
    return splits


